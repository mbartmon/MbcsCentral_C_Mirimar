			frmMail.Show();
			frmMail.BringIntoView();

			//Dim interaction As Email.Net.Common.Configurations.EInteractionType
			//If TSLCheckBox.IsChecked Then
			//Interaction = Email.Net.Common.Configurations.EInteractionType.StartTLS
